import { GameRegion } from './generated/regions';

// Define a custom type for the possible Game Modes
export const gameModes = ['training', 'daily'] as const;
export type GameMode = (typeof gameModes)[number];

// Define a custom type for the possible selections
export const countrySelections = ['all', 'independent'] as const;
export type CountrySelection = (typeof countrySelections)[number];

// Define a custom type for the possible Features
export const features = ['capitals', 'countries'] as const;
export type Feature = (typeof features)[number];

export function formatSingularFeature(feature: Feature): string {
  switch (feature) {
    case 'countries':
      return 'country';
    case 'capitals':
      return 'capital';
  }
}

export function formatRegion(region: GameRegion): string {
  switch (region) {
    case 'Africa':
    case 'Asia':
    case 'Europe':
    case 'Oceania':
      return region;
    case 'Americas':
    case 'World':
      return `the ${region}`;
  }
}

// Define a custom type for the possible attributes of a feature
export const attributes = ['capital', 'name', 'flag'] as const;
export type Attribute = (typeof attributes)[number];

export interface GameParamObject {
  gamemode: GameMode;
  region: GameRegion;
  selection: CountrySelection;
  feature: Feature;
}

export interface CompleteGameParams extends GameParamObject {
  knownAttributes: string;
  guessAttributes: string;
}

export interface GameParams {
  params: GameParamObject;
}

// Next.js passes the route params to pages as a promise
export interface GamePageProps {
  params: Promise<GameParamObject>;
}

export interface CompleteGamePageProps {
  params: Promise<CompleteGameParams>;
}

// Next.js types the parent params passed to `generateStaticParams` as plain strings
// They only ever contain the values generated by the parent layouts, so they can safely be narrowed
export interface StaticParamsProps {
  params: Record<string, string | string[] | undefined>;
}

export function toCompleteGameParams(
  props: StaticParamsProps
): CompleteGameParams {
  return props.params as unknown as CompleteGameParams;
}
